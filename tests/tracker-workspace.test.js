import test from 'node:test';
import assert from 'node:assert/strict';
import { sampleDocument, addCustomSection } from '../src/model.js';
import { createWorkspace, addApplication, updateApplication, duplicateDocument, updateActiveDocument, deleteDocument, captureApplicationSubmission, applicationSubmission, removeApplicationSubmission, copySubmissionToLibrary, addApplicationTask, updateApplicationTask, removeApplicationTask, addApplicationCustomField, updateApplicationCustomField, removeApplicationCustomField, parseWorkspace, serialiseWorkspace, mergeWorkspace, validateWorkspace } from '../src/workspace.js';

const makeWorkspace = () => addApplication(createWorkspace(sampleDocument()), 'job');
test('0.2 tracker records migrate with every supplied field retained and additive defaults only', () => {
  const old = makeWorkspace();
  old.applications[0] = { id: 'job', company: 'Zoë & Co', role: '日本語 designer', url: 'https://example.test/role', status: 'interview', appliedDate: '2026-10-09', followUpDate: '2026-10-12', notes: '<script>literal</script> £40,000', cvId: 'initial-cv' };
  const raw = JSON.stringify(old); const parsed = parseWorkspace(raw);
  for (const [key, value] of Object.entries(old.applications[0])) assert.deepEqual(parsed.applications[0][key], value);
  assert.deepEqual(parsed.applications[0].tasks, []);
  assert.deepEqual(parsed.applications[0].submissions, []);
  assert.deepEqual(parsed.applications[0].customFields, []);
  assert.equal(parsed.applications[0].archived, false);
  assert.equal(JSON.stringify(old), raw);
  assert.deepEqual(parseWorkspace(serialiseWorkspace(parsed)), parsed);
});
test('submitted CV and letter stay independent through source edits, rename, deletion and library restoration', () => {
  let ws = makeWorkspace();
  ws.documents[0].document.coverLetter.body = 'Exact letter with £ and 日本語.';
  ws.documents[0].document.jobAd = 'Private job description';
  ws.documents[0].document.hiddenSections = ['education'];
  const before = structuredClone(ws.documents[0].document);
  ws = captureApplicationSubmission(ws, 'job', 'submitted', 'Initial application', '2026-10-10T10:00:00.000Z');
  ws = updateActiveDocument(ws, { ...ws.documents[0].document, profile: { ...ws.documents[0].document.profile, name: 'Later name' }, coverLetter: { ...ws.documents[0].document.coverLetter, body: 'Different letter' } });
  ws.documents[0].name = 'Renamed later';
  assert.deepEqual(applicationSubmission(ws, 'job', 'submitted').document, before);
  assert.equal(applicationSubmission(ws, 'job', 'submitted').cvName, 'My CV');
  const detached = applicationSubmission(ws, 'job', 'submitted'); detached.document.profile.name = 'Caller mutation';
  assert.deepEqual(applicationSubmission(ws, 'job', 'submitted').document, before);
  ws = duplicateDocument(ws, 'spare', 'Spare'); ws = deleteDocument(ws, 'initial-cv');
  assert.equal(ws.applications[0].cvId, '');
  assert.deepEqual(applicationSubmission(ws, 'job', 'submitted').document, before);
  const restored = copySubmissionToLibrary(ws, 'job', 'submitted', 'restored');
  assert.equal(restored.activeId, 'restored');
  assert.deepEqual(restored.documents.at(-1).document, before);
  assert.equal(restored.applications[0].submissions.length, 1);
  assert.throws(() => updateApplication(restored, 'job', 'submissions', []), /Unknown/);
});
test('archive retains tasks, custom fields and submitted copies; removing attachments is explicit and immutable', () => {
  let ws = makeWorkspace(); ws = addApplicationTask(ws, 'job', 'task'); ws = addApplicationCustomField(ws, 'job', 'field');
  ws = captureApplicationSubmission(ws, 'job', 'copy', '', '2026-10-10T11:00:00.000Z');
  const archived = updateApplication(ws, 'job', 'archived', true);
  assert.equal(archived.applications[0].archived, true);
  for (const key of ['tasks', 'customFields', 'submissions']) assert.deepEqual(archived.applications[0][key], ws.applications[0][key]);
  const removed = removeApplicationSubmission(archived, 'job', 'copy');
  assert.equal(removed.applications[0].submissions.length, 0);
  assert.equal(archived.applications[0].submissions.length, 1);
  assert.throws(() => captureApplicationSubmission(updateApplication(ws, 'job', 'cvId', ''), 'job', 'missing', ''), /Link a CV/);
  assert.throws(() => updateApplication(ws, 'job', 'archived', 'true'), /true or false/);
});
test('task and custom-field mutations are bounded, validated, independent and reject unknown identifiers', () => {
  const original = makeWorkspace();
  let ws = addApplicationTask(original, 'job', 'task'); ws = updateApplicationTask(ws, 'job', 'task', 'title', 'Send thank-you');
  ws = updateApplicationTask(ws, 'job', 'task', 'dueDate', '2026-10-11'); ws = updateApplicationTask(ws, 'job', 'task', 'done', true);
  ws = addApplicationCustomField(ws, 'job', 'field'); ws = updateApplicationCustomField(ws, 'job', 'field', 'label', 'Salary');
  ws = updateApplicationCustomField(ws, 'job', 'field', 'value', '=literal £40,000\n<script>text</script>');
  assert.equal(original.applications[0].tasks.length, 0);
  assert.equal(ws.applications[0].tasks[0].done, true);
  assert.throws(() => updateApplicationTask(ws, 'job', 'task', 'dueDate', '2026-02-30'), /valid date/);
  assert.throws(() => updateApplicationTask(ws, 'job', 'task', 'done', 'yes'), /true or false/);
  assert.throws(() => updateApplicationTask(ws, 'job', 'missing', 'title', 'Oops'), /not found/);
  assert.throws(() => updateApplicationCustomField(ws, 'job', 'field', 'value', 'x'.repeat(2001)), /2000/);
  assert.throws(() => addApplicationTask(ws, 'job', 'task'), /unique/);
  assert.throws(() => updateApplicationCustomField(ws, 'job', 'field', 'id', 'replacement'), /Unknown/);
  assert.equal(removeApplicationTask(ws, 'job', 'task').applications[0].tasks.length, 0);
  assert.equal(removeApplicationCustomField(ws, 'job', 'field').applications[0].customFields.length, 0);
  assert.deepEqual(parseWorkspace(serialiseWorkspace(ws)), ws);
});
test('workspace merging remaps mutable links but preserves exact immutable submission payload and nested fields', () => {
  let incoming = addApplicationTask(makeWorkspace(), 'job', 'task');
  incoming = captureApplicationSubmission(incoming, 'job', 'copy', 'Sent copy', '2026-10-10T12:00:00.000Z');
  incoming = updateApplication(incoming, 'job', 'archived', true);
  const target = makeWorkspace(); let number = 0;
  const merged = mergeWorkspace(target, incoming, () => `import-${++number}`);
  const app = merged.applications.at(-1);
  assert.equal(app.id, 'import-2'); assert.equal(app.cvId, 'import-1'); assert.equal(app.archived, true);
  assert.deepEqual(app.submissions, incoming.applications[0].submissions);
  assert.deepEqual(app.tasks, incoming.applications[0].tasks);
  assert.deepEqual(target, makeWorkspace());
  assert.deepEqual(parseWorkspace(serialiseWorkspace(merged)), merged);
});
test('submission count and shared workspace byte bounds reject additions without changing prior records', () => {
  let ws = makeWorkspace();
  for (let i = 0; i < 8; i++) ws = captureApplicationSubmission(ws, 'job', `copy-${i}`, `Copy ${i}`, '2026-10-10T12:00:00.000Z');
  const old = serialiseWorkspace(ws);
  assert.throws(() => captureApplicationSubmission(ws, 'job', 'copy-9', 'Another'), /8/);
  assert.equal(serialiseWorkspace(ws), old);
  let doc = sampleDocument();
  for (let i = 0; i < 18; i++) { doc = addCustomSection(doc, `large-${i}`, 'Large section'); doc.customSections.at(-1).content = 'x'.repeat(30000); }
  let large = addApplication(createWorkspace(doc), 'job');
  large = captureApplicationSubmission(large, 'job', 'one', 'One');
  large = captureApplicationSubmission(large, 'job', 'two', 'Two');
  large = captureApplicationSubmission(large, 'job', 'three', 'Three');
  large = captureApplicationSubmission(large, 'job', 'four', 'Four');
  large = captureApplicationSubmission(large, 'job', 'five', 'Five');
  const previous = serialiseWorkspace(large);
  assert.throws(() => captureApplicationSubmission(large, 'job', 'six', 'Too large'), /4 MB/);
  assert.equal(serialiseWorkspace(large), previous);
  assert.deepEqual(validateWorkspace(large), large);
});
